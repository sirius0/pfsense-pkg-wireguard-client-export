wgce_test('safe suggestions derive tunnel, DDNS, DNS and local route defaults without persistence', static function (): void {
    wgce_config_reset(wgclientexport_default_settings());
    $GLOBALS['wgce_config_backend']['events'] = [];
    $tunnel = [
        'name' => 'tun_wg0',
        'listen_port' => 51820,
        'addresses' => ['row' => [
            ['address' => '10.66.66.1', 'mask' => '24'],
            ['address' => '2001:db8::1', 'mask' => '64'],
        ]],
    ];
    $context = [
        'dns_servers' => [
            '8.8.8.8',
            ['item' => ['1.1.1.1', '8.8.8.8', '192.168.1.1', '127.0.0.1']],
            'invalid',
        ],
        'ddns_records' => [
            ['host' => 'VPN.Example.Test'],
            ['hostname' => 'vpn.example.test'],
            ['host' => 'disabled.example.test', 'enable' => true],
        ],
        'wan_ipv4' => '93.184.216.34',
        'local_networks' => [
            ['address' => '192.168.1.118', 'mask' => '24'],
            '172.16.8.4/23',
            '192.168.1.0/24',
            '0.0.0.0/0',
            'not-a-route',
        ],
    ];

    $suggested = wgclientexport_suggest_tunnel_settings($tunnel, $context);

    wgce_assert_same('tun_wg0', $suggested['tunnel_id']);
    wgce_assert_same('yes', $suggested['enabled']);
    wgce_assert_same('10.66.66.0/24', $suggested['client_pool_ipv4']);
    wgce_assert_same('vpn.example.test', $suggested['endpoint_host']);
    wgce_assert_same('51820', $suggested['endpoint_port']);
    wgce_assert_same(
        ['item' => ['8.8.8.8', '1.1.1.1', '192.168.1.1']],
        $suggested['dns_ipv4']
    );
    wgce_assert_same('25', $suggested['persistent_keepalive']);
    wgce_assert_same(
        ['item' => ['192.168.1.0/24', '172.16.8.0/23']],
        $suggested['local_routes_ipv4']
    );
    wgce_assert_same(['item' => []], $suggested['reservations_ipv4']);
    wgce_assert_false(wgclientexport_contains_secret_field($suggested));
    wgce_assert_same([], $GLOBALS['wgce_config_backend']['events']);
    wgce_assert_same([], $GLOBALS['wgce_wireguard_mutations']);
});

