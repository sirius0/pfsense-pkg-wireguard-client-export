function wgce_config_events_of_type(string $type): array
{
    return array_values(array_filter(
        $GLOBALS['wgce_config_backend']['events'],
        static fn(array $event): bool => $event[0] === $type
    ));
}

wgce_test('pfSense package settings use the indexed config row path', static function (): void {
    wgce_config_reset(wgce_config_fixture());

    $settings = wgclientexport_get_settings();

    wgce_assert_same('installedpackages/wgclientexport/config/0', WGCLIENTEXPORT_CONFIG_PATH);
