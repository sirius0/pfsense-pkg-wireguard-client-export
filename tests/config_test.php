wgce_test('a genuinely public WAN address is suggested when DDNS is not unique', static function (): void {
    $public = wgclientexport_suggest_endpoint_host([], '93.184.216.34');
    $ambiguous = wgclientexport_suggest_endpoint_host(
        [['host' => 'first.example.test'], ['host' => 'second.example.test']],
        '93.184.216.34'
    );

    wgce_assert_same('93.184.216.34', $public);
    wgce_assert_same('93.184.216.34', $ambiguous);
    foreach ([
        '0.0.0.1',
        '10.1.2.3',
        '100.64.0.1',
        '127.0.0.1',
        '169.254.1.1',
        '172.16.0.1',
        '192.0.2.1',
        '192.168.1.118',
        '198.18.0.1',
        '198.51.100.1',
        '203.0.113.10',
        '224.0.0.1',
        '240.0.0.1',
    ] as $nonPublic) {
        wgce_assert_same('', wgclientexport_suggest_endpoint_host([], $nonPublic));
    }
});

