$GLOBALS['wgce_config_backend'] = [];
$GLOBALS['wgce_wireguard_mutations'] = [];

function wgce_config_reset(mixed $value): void
{
    $GLOBALS['wgce_config_backend'] = [
        'values' => [
            'installedpackages/wgclientexport/config' => [0 => $value],
            'installedpackages/wgclientexport/config/0' => $value,
        ],
        'events' => [],
    ];
    $GLOBALS['wgce_wireguard_mutations'] = [];
}

function config_get_path(string $path, mixed $default = null): mixed
{
    $GLOBALS['wgce_config_backend']['events'][] = ['get', $path];
    return array_key_exists($path, $GLOBALS['wgce_config_backend']['values'])
        ? $GLOBALS['wgce_config_backend']['values'][$path] : $default;
}

function config_set_path(string $path, mixed $value): mixed
{
    $GLOBALS['wgce_config_backend']['events'][] = ['set', $path, $value];
    $GLOBALS['wgce_config_backend']['values'][$path] = $value;
    if ($path === 'installedpackages/wgclientexport/config/0') {
        $parent = $GLOBALS['wgce_config_backend']['values']['installedpackages/wgclientexport/config'] ?? [];
        $parent = is_array($parent) ? $parent : [];
        $parent[0] = $value;
        $GLOBALS['wgce_config_backend']['values']['installedpackages/wgclientexport/config'] = $parent;
    }
    return null;
}

function write_config(string $message): mixed
{
    $GLOBALS['wgce_config_backend']['events'][] = ['write', $message];
    return null;
}

function wg_do_peer_post(array $payload): array
{
    $GLOBALS['wgce_wireguard_mutations'][] = ['create_peer', $payload];
    return [];
}

function wg_tunnel_sync(array $tunnels, bool $force = true, bool $reload = true): array
{
    $GLOBALS['wgce_wireguard_mutations'][] = ['sync_tunnel', $tunnels, $force, $reload];
    return [];
}

function wg_delete_peer(int $index): array
{
    $GLOBALS['wgce_wireguard_mutations'][] = ['delete_peer', $index];
    return [];
}

