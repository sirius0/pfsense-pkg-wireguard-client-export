wgce_test('install repairs scalar and malformed empty package rows with secret-free defaults', static function (): void {
    $malformedStates = [
        'scalar generated by the old unindexed path' => '1',
        'empty array' => [],
        'non-array tunnels node' => ['schema_version' => '1', 'tunnels' => '1'],
    ];

    foreach ($malformedStates as $case => $malformed) {
        wgce_config_reset($malformed);

        $result = wgclientexport_install();

        wgce_assert_same([], $result['input_errors'], 'Unexpected repair error for ' . $case);
        wgce_assert_true($result['changes'], 'Malformed state was not repaired for ' . $case);
        wgce_assert_same(wgclientexport_default_settings(), $result['result']);
        $sets = wgce_config_events_of_type('set');
        wgce_assert_same(1, count($sets), 'Repair did not perform exactly one set for ' . $case);
        wgce_assert_same('installedpackages/wgclientexport/config/0', $sets[0][1]);
        wgce_assert_same(wgclientexport_default_settings(), $sets[0][2]);
        wgce_assert_same(
            [0 => wgclientexport_default_settings()],
            $GLOBALS['wgce_config_backend']['values']['installedpackages/wgclientexport/config']
        );
        wgce_assert_same(1, count(wgce_config_events_of_type('write')));
        wgce_assert_false(wgclientexport_contains_secret_field($sets[0][2]));
        wgce_assert_same([], $GLOBALS['wgce_wireguard_mutations']);
    }
});

